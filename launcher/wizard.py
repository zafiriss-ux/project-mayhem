"""
TITAN Launcher — First-Run Setup Wizard

Interactive console wizard for initial configuration.
Creates .env file with Garmin, Telegram, and OpenAI credentials.

Workflow:
  1. Check if .env exists
  2. If not, run interactive wizard
  3. Validate inputs (basic sanity checks)
  4. Write .env to ~/Documents/TITAN/.env
  5. Set proper permissions (chmod 600 on Linux/macOS)
"""

import base64
import os
import sys
from pathlib import Path

from launcher.errors import ConfigurationError
from launcher.validator import get_data_directory

# ══════════════════════════════════════════════════════════════════════════════
# .env Management
# ══════════════════════════════════════════════════════════════════════════════

def get_env_path() -> Path:
    """Return path to .env file in data directory."""
    return get_data_directory() / '.env'


def env_exists() -> bool:
    """Check if .env file already exists."""
    return get_env_path().exists()


def load_env() -> dict[str, str]:
    """
    Load existing .env file.

    Returns:
        Dict of KEY=VALUE pairs
    """
    env_path = get_env_path()
    if not env_path.exists():
        return {}

    env_vars = {}
    try:
        with open(env_path, encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    key, value = line.split('=', 1)
                    env_vars[key.strip()] = value.strip()
    except Exception:
        pass  # Return empty dict if parse fails
    return env_vars


def write_env(config: dict[str, str]) -> None:
    """
    Write .env file to data directory.

    Args:
        config: Dict of KEY=VALUE pairs
    """
    env_path = get_env_path()
    try:
        # SP-06: 600 before the first byte. A new file is created 600; an existing one
        # is truncated, then set to 600 before anything is written into it.
        fd = os.open(env_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        if hasattr(os, "fchmod"):  # POSIX only
            try:
                os.fchmod(fd, 0o600)
            except BaseException:
                os.close(fd)
                raise
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write("# TITAN OS v5.7 Configuration\n")
            f.write("# Generated by launcher setup wizard\n\n")
            for key, value in config.items():
                f.write(f"{key}={value}\n")

        # Set restrictive permissions on Linux/macOS (600 = owner read/write only)
        try:
            import stat
            env_path.chmod(stat.S_IRUSR | stat.S_IWUSR)
        except Exception:
            pass  # Windows doesn't support chmod

        print(f"\n✓ Configuration saved to: {env_path}\n")
    except Exception as e:
        raise ConfigurationError(
            code='CFG_WRITE_FAILED',
            message=f"Failed to write .env file: {e}",
            remediation="Check folder permissions.",
        ) from e


GARMIN_TOKEN_KEY = 'TITAN_GARTH_TOKEN_KEY'


def ensure_garmin_token_key() -> str:
    """Return the key that encrypts the saved Garmin session, creating it once.

    The kernel refuses to save the Garmin session without this key, so without
    it TITAN.exe logged in to Garmin with the password on every start. The key
    is appended to .env so the saved session can be read on the next start.
    """
    key = load_env().get(GARMIN_TOKEN_KEY)
    if key:
        return key
    key = base64.urlsafe_b64encode(os.urandom(32)).decode('ascii')  # Fernet key format
    env_path = get_env_path()
    if env_path.exists():
        text = env_path.read_text(encoding='utf-8')
        separator = '' if not text or text.endswith('\n') else '\n'
        with open(env_path, 'a', encoding='utf-8') as f:
            f.write(f"{separator}{GARMIN_TOKEN_KEY}={key}\n")
    return key


# ══════════════════════════════════════════════════════════════════════════════
# Input Validation
# ══════════════════════════════════════════════════════════════════════════════

def validate_garmin_username(username: str) -> bool:
    """Basic sanity check for Garmin username (email or username)."""
    return len(username) >= 3 and ('@' in username or len(username) <= 50)


def validate_telegram_token(token: str) -> bool:
    """Basic sanity check for Telegram bot token format."""
    # Expected format: <bot_id>:<token>  e.g. 1234567890:YOUR_BOT_TOKEN
    return ':' in token and len(token) >= 20


def validate_telegram_chat_id(chat_id: str) -> bool:
    """Validate Telegram chat ID as a signed integer string."""
    return chat_id.lstrip('-').isdigit()


def validate_openai_key(key: str) -> bool:
    """Basic sanity check for OpenAI API key format."""
    # Expected: sk-... (starts with sk- prefix)
    return key.startswith('sk-') and len(key) > 20


# ══════════════════════════════════════════════════════════════════════════════
# Interactive Wizard
# ══════════════════════════════════════════════════════════════════════════════

def prompt_input(prompt: str, validator=None, optional: bool = False) -> str:
    """
    Prompt user for input with optional validation.

    Args:
        prompt:    Text to display
        validator: Function to validate input (returns bool)
        optional:  If True, allow empty input

    Returns:
        User input (stripped)
    """
    while True:
        try:
            value = input(f"   {prompt}: ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\n\n⚠️  Setup cancelled by user.")
            sys.exit(0)

        if not value and optional:
            return ''
        if not value:
            print("      ⚠️  This field is required.")
            continue
        if validator and not validator(value):
            print("      ⚠️  Invalid format. Try again.")
            continue
        return value


def run_wizard() -> dict[str, str]:
    """
    Run interactive setup wizard.

    Returns:
        Dict of configuration keys
    """
    print("\n" + "=" * 70)
    print("   TITAN OS v5.7 — First-Time Setup")
    print("=" * 70)
    print("\nWelcome! Let's configure your TITAN installation.\n")
    print("You'll need:")
    print("  • Garmin Connect credentials (username & password)")
    print("  • Telegram bot token (get from @BotFather)")
    print("  • OpenAI API key (optional — for LLM coaching)\n")

    config = {}

    # 1. Garmin credentials
    print("── Garmin Connect ──────────────────────────────────────────────────\n")
    config['GARMIN_EMAIL'] = prompt_input(
        "Garmin username or email",
        validator=validate_garmin_username,
    )
    config['GARMIN_PASSWORD'] = prompt_input("Garmin password")

    # 2. Telegram bot
    print("\n── Telegram Bot ────────────────────────────────────────────────────\n")
    print("   Create a bot with @BotFather and paste the token here.")
    config['TELEGRAM_BOT_TOKEN'] = prompt_input(
        "Telegram bot token",
        validator=validate_telegram_token,
    )
    config['TELEGRAM_CHAT_ID'] = prompt_input(
        "Your Telegram chat ID (send /start to @userinfobot to get it)",
        validator=validate_telegram_chat_id,
    )

    # 3. OpenAI API key (optional)
    print("\n── OpenAI API (Optional) ───────────────────────────────────────────\n")
    print("   TITAN can use GPT-4 for coaching narratives.")
    print("   Leave blank to skip (you can add it later).\n")
    openai_key = prompt_input(
        "OpenAI API key (sk-...)",
        validator=validate_openai_key,
        optional=True,
    )
    if openai_key:
        config['OPENAI_API_KEY'] = openai_key

    # 4. Weather API key (optional)
    print("\n── Weather API (Optional) ──────────────────────────────────────────\n")
    print("   For real-time weather data (OpenWeatherMap or similar).")
    print("   Leave blank to skip.\n")
    weather_key = prompt_input("Weather API key", optional=True)
    if weather_key:
        config['WEATHER_API_KEY'] = weather_key

    print("\n" + "=" * 70)
    print("   Setup Complete!")
    print("=" * 70)

    return config


# ══════════════════════════════════════════════════════════════════════════════
# Entry Point
# ══════════════════════════════════════════════════════════════════════════════

def ensure_config() -> bool:
    """
    Ensure .env exists. If not, run wizard.

    Returns:
        True if config is ready, False if setup failed/cancelled
    """
    if env_exists():
        env_vars = load_env()
        garmin_username = env_vars.get('GARMIN_USERNAME') or env_vars.get('GARMIN_EMAIL')
        required_values = [
            garmin_username,
            env_vars.get('GARMIN_PASSWORD'),
            env_vars.get('TELEGRAM_BOT_TOKEN'),
            env_vars.get('TELEGRAM_CHAT_ID'),
        ]

        if all(required_values):
            print("✓ Configuration found.\n")
            return True

        print("⚠ Configuration file exists but is incomplete.\n")
        return False

    # Run wizard
    try:
        config = run_wizard()
        write_env(config)
    except Exception as e:
        print(f"\n❌ Setup failed: {e}\n")
        return False
    else:
        return True
